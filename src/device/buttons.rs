#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn unique_masks() {
        let mut seen = HashSet::new();
        for (off, mask, _) in BUTTON_TABLE {
            assert!(seen.insert((*off, *mask)), "dup {off}:{mask:#x}");
        }
    }
}
