/// Buttons we care about for v1, plus a dump-friendly id for the rest.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]
pub enum Button {
    EncoderPress,
    EncoderUp,
    EncoderRight,
    EncoderDown,
    EncoderLeft,
    Shift,
    Group(u8), // 0=A .. 7=H
    Notes,
    Volume,
    Swing,
    Tempo,
    NoteRepeat,
    Lock,
    PadMode,
    Keyboard,
    Chords,
    Step,
    FixedVel,
    Scene,
    Pattern,
    Events,
    Variation,
    Duplicate,
    Select,
    Solo,
    Mute,
    Pitch,
    Mod,
    Perform,
    Restart,
    Erase,
    Tap,
    Follow,
    Play,
    Rec,
    Stop,
    Macro,
    Settings,
    ArrowRight,
    Sampling,
    Mixer,
    Plugin,
    Channel,
    Arranger,
    Browser,
    ArrowLeft,
    File,
    Auto,
    Top(u8), // 0..7
    EncoderTouch,
    KnobTouch(u8), // 0..7
}

